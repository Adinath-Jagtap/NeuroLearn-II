class TranslationDict(dict):
    """A dictionary with English fallback if key missing in current language."""
    def __init__(self, current_dict, fallback_dict):
        super().__init__(current_dict)
        self.fallback = fallback_dict

    def __getitem__(self, key):
        if key in self:
            return super().__getitem__(key)
        return self.fallback.get(key, key)

    def get(self, key, default=None):
        if key in self:
            return super().__getitem__(key)
        return self.fallback.get(key, default if default is not None else key)


def get_translations(language="en"):
    """Return TranslationDict for the specified language, falling back to English."""
    lang_code = language.lower() if language else "en"
    current = TRANSLATIONS.get(lang_code, TRANSLATIONS["en"])
    return TranslationDict(current, TRANSLATIONS["en"])
